// Generates supabase/seed.sql from the edition bundled in index.html.
// Usage: node tools/gen_seed.js   (needs: npm i jsdom)
const {JSDOM} = require('jsdom'); const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..');
let html = fs.readFileSync(path.join(root,'index.html'),'utf8')
  .replace(/<script src=[^>]+><\/script>/g,'')
  .replace(/\n<\/script>(?![\s\S]*<\/script>)/, '\nwindow.__D={S,EV,C,CE,FXR,GULF,GLOBAL,CMD,HORO};\n</script>');
const w = new JSDOM(html,{runScripts:'dangerously',beforeParse(w){w.scrollTo=()=>{};}}).window;
const {S,EV,C,CE,FXR,GULF,GLOBAL,CMD,HORO} = w.__D;
const q = v => v===null||v===undefined ? 'null' : typeof v==='number' ? String(v) : typeof v==='boolean' ? String(v) : `'${String(v).replace(/'/g,"''")}'`;
const j = o => `'${JSON.stringify(o).replace(/'/g,"''")}'::jsonb`;
const slug = s => s.toLowerCase().normalize('NFKD').replace(/[^\w]+/g,'-').replace(/^-|-$/g,'').slice(0,60);
let out = ['-- BeeNews seed: first edition, 28 Oct 2026. Generated by tools/gen_seed.js — do not edit by hand.',
 '-- Sensitive (health/political) stories are seeded as in_review: an editor must approve them before they appear.',''];
out.push('insert into public.stories (id,section,country,label,sensitive,editor_approved,headline,summary,publisher,published_at,date_only,url,link_is_section,also_reported,is_lead,translations,status) values');
out.push(S.map(s=>{
  const tr={}; for(const l of ['ar','fr','de']) if(C[l]&&C[l][s.id]) tr[l]=C[l][s.id];
  return `(${q(s.id)},${q(s.sec)},${q(s.country)},${q(s.lab)},${!!s.sens},false,${q(s.h)},${q(s.s)},${q(s.pub)},${q(s.t)},${!!s.dateOnly},${q(s.url)},${!!s.section},${q(s.also)},${!!s.lead},${j(tr)},'${s.sens?'in_review':'published'}')`;
}).join(',\n')+'\non conflict (id) do nothing;\n');
out.push('insert into public.events (id,name,category,emirate,start_date,end_date,end_approx,venue,entry,description,label,publisher,url,also_reported,rescheduled,translations) values');
out.push(EV.map(e=>{
  const tr={}; for(const l of ['ar','fr','de']) if(CE[l]&&CE[l][e.n]) tr[l]=CE[l][e.n];
  return `(${q(slug(e.n))},${q(e.n)},${q(e.cat)},${q(e.em)},${q(e.start)},${q(e.end)},${!!e.approx},${q(e.venue)},${q(e.entry)},${q(e.d)},${q(e.lab)},${q(e.pub)},${q(e.url)},${q(e.also)},${!!e.resched},${j(tr)})`;
}).join(',\n')+'\non conflict (id) do nothing;\n');
out.push('insert into public.fx_rates (code,aed_per_unit,per_units,source,as_of,sort) values');
out.push(FXR.map((f,i)=>`(${q(f.c)},${f.r.toFixed(8)},${f.per||1},${q(f.src)},${q(f.d)},${i})`).join(',\n')+'\non conflict (code) do nothing;\n');
const quotes=[...GULF.map((g,i)=>({id:'gulf-'+slug(g.n),kind:'gulf',name:g.n,country_key:g.k,value:g.v,ch:g.ch,sort:i})),
  ...GLOBAL.map((g,i)=>({id:'global-'+slug(g.n),kind:'global',name:g.n,country_key:null,value:g.v,ch:g.ch,sort:i})),
  ...CMD.map((c,i)=>({id:'cmd-'+c.k,kind:'commodity',name:c.k,country_key:null,value:c.v,ch:c.ch,sort:i}))];
out.push('insert into public.market_quotes (id,kind,name,country_key,value,change_pct,as_of,sort) values');
out.push(quotes.map(m=>`(${q(m.id)},${q(m.kind)},${q(m.name)},${q(m.country_key)},${m.value},${m.ch},'2026-10-27',${m.sort})`).join(',\n')+'\non conflict (id) do nothing;\n');
out.push('insert into public.horoscopes (day,sign,lang,body) values');
const hr=[]; for(const l of Object.keys(HORO)) for(const [sg,b] of Object.entries(HORO[l])) hr.push(`('2026-10-28',${q(sg)},${q(l)},${q(b)})`);
out.push(hr.join(',\n')+'\non conflict do nothing;\n');
fs.mkdirSync(path.join(root,'supabase'),{recursive:true});
fs.writeFileSync(path.join(root,'supabase','seed.sql'), out.join('\n'));
console.log(`seed.sql: ${S.length} stories, ${EV.length} events, ${FXR.length} rates, ${quotes.length} quotes, ${hr.length} horoscope rows`);
